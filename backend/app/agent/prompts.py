def format_context(results: list[dict]) -> str:
    """把检索候选格式化为知识库上下文字段。"""
    lines = []
    for r in results:
        faq = r["faq"]
        lines.append(
            f"[{faq.id}]（{faq.category}，{faq.risk_level}风险）\n"
            f"标准问法：{faq.standard_question}\n答案：{faq.answer}"
        )
    return "\n\n".join(lines)


def format_history(messages: list[dict], window: int = settings.HISTORY_WINDOW_TURNS) -> str:
    """格式化最近 N 轮对话历史。"""
    recent = messages[-window * 2:] if messages else []
    lines = []
    for m in recent:
        role = "用户" if m["role"] == "user" else "客服"
        lines.append(f"{role}：{m['content']}")
    return "\n".join(lines) if lines else "（无）"
